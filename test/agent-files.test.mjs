import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { MARKER, VENDORS, buildAgentFiles, checkAgentFiles, renderClaude, renderCodex, renderGemini } from '../server/ai/agent-files.mjs';
import { runSync } from '../scripts/sync-agents.mjs';

// The native agent files (id158, or68): one spec, each AI's own spelling, never edited by hand.

const SPEC = {
  id: 'sm-alpha', type: 'specialist', model: 'sonnet', effort: 'medium', classes: ['read', 'edit', 'shell'],
  description: 'Owner of the Alpha part: "quoted" and [code].',
  system: 'You own Alpha.\nA path C:\\dev and a """ run.\nEnd.',
};

test('Claude: name, quoted description, the tools of the classes, the policy model and level, the generated note', () => {
  const text = renderClaude(SPEC);
  const [, front, body] = text.split('---\n');
  assert.match(front, /^name: sm-alpha\n/);
  assert.match(front, /description: "Owner of the Alpha part: \\"quoted\\" and \[code\]\."\n/);
  assert.match(front, /tools: Read, Glob, Grep, Edit, Write, MultiEdit, Bash, PowerShell\n/);
  assert.match(front, /model: sonnet\neffort: medium\n$/);
  assert.ok(body.includes(MARKER) && body.includes('You own Alpha.'));
});

test('an empty tool list is refused: it could mean "inherit them all" to the AI', () => {
  assert.throws(() => renderClaude({ ...SPEC, classes: ['read'] }, { toolClasses: { claude: {} } }), /no claude tools/);
  assert.throws(() => renderGemini({ ...SPEC, classes: ['read'] }, { toolClasses: {} }), /no gemini tools/);
});

test('Gemini: its own tool names, and no model of another company', () => {
  const text = renderGemini({ ...SPEC, classes: ['read', 'shell'] });
  assert.match(text, /tools:\n  - read_file\n  - list_directory\n  - glob\n  - grep_search\n  - run_shell_command\n---/);
  assert.doesNotMatch(text, /model:|effort:|Bash|Edit/);
});

test('Codex: the three required fields, strings escaped, no model, no tools', () => {
  const text = renderCodex(SPEC);
  assert.match(text, /^# generated by session-map/);
  assert.match(text, /\nname = "sm-alpha"\n/);
  assert.match(text, /\ndescription = "Owner of the Alpha part: \\"quoted\\" and \[code\]\."\n/);
  assert.match(text, /\ndeveloper_instructions = """\nYou own Alpha\.\nA path C:\\\\dev and a \\"\\"\\" run\.\nEnd\.\n"""\n$/);
  assert.doesNotMatch(text, /\nmodel|tools|sandbox/);
});

test('buildAgentFiles: stable, one file per spec per vendor, in each vendor\'s folder; an unknown vendor throws', () => {
  const a = buildAgentFiles([SPEC]);
  assert.deepEqual(a.map((f) => f.path), ['.claude/agents/sm-alpha.md', '.gemini/agents/sm-alpha.md', '.codex/agents/sm-alpha.toml']);
  assert.deepEqual(buildAgentFiles([SPEC]), a);
  assert.deepEqual(buildAgentFiles([SPEC], { vendors: ['codex'] }).map((f) => f.vendor), ['codex']);
  assert.throws(() => buildAgentFiles([SPEC], { vendors: ['nope'] }), /unknown vendor/);
  assert.deepEqual(VENDORS, ['claude', 'gemini', 'codex']);
});

test('checkAgentFiles: missing, changed and stale; an agent somebody wrote by hand is never called stale', () => {
  const built = buildAgentFiles([SPEC], { vendors: ['claude'] });
  const disk = new Map([
    ['/p/.claude/agents/sm-alpha.md', `${built[0].content}x`],
    ['/p/.claude/agents/sm-gone.md', `<!-- ${MARKER} -->`],
    ['/p/.claude/agents/sm-mine.md', 'my own agent'],
    ['/p/.claude/agents/other.md', `<!-- ${MARKER} -->`],
  ]);
  const read = (p) => disk.get(p.replaceAll('\\', '/')) ?? null;
  const list = () => ['sm-alpha.md', 'sm-gone.md', 'sm-mine.md', 'other.md'];
  const res = checkAgentFiles(built, { root: '/p', read, list, vendors: ['claude'] });
  assert.deepEqual([res.missing, res.changed, res.stale, res.clean], [[], ['.claude/agents/sm-alpha.md'], ['.claude/agents/sm-gone.md'], false]);
  assert.equal(checkAgentFiles(built, { root: '/p', read: (p) => (p.endsWith('sm-alpha.md') ? built[0].content : null), list: () => [], vendors: ['claude'] }).clean, true);
});

test('the sync writes from a real map, is clean on a second check, follows an edit, and never overwrites a hand-written agent', async () => {
  const root = mkdtempSync(join(tmpdir(), 'sm-agents-'));
  try {
    const dir = join(root, 'docs', 'architecture');
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'README.md'), '# Parts\n\n## Engine\n\n- [Alpha](alpha.md)\n');
    const part = (rule) => `# Alpha\n\nAlpha works.\n\n## Where in the code\n\n- \`server/alpha/\`\n\n## Rules that must not break\n\n- ${rule}\n\n## What's missing\n\n- [ ] **Claude:** x \`al01\`\n`;
    writeFileSync(join(dir, 'alpha.md'), part('First rule.'));
    const files = ['server/alpha/a.mjs', 'test/alpha-a.test.mjs'];
    const first = await runSync({ root, files });
    assert.equal(first.ok, true);
    assert.equal(first.written, 18, '1 specialist + 5 roles, three vendors');
    const claude = readFileSync(join(root, '.claude', 'agents', 'sm-alpha.md'), 'utf8');
    assert.match(claude, /First rule\./);
    assert.ok(existsSync(join(root, '.codex', 'agents', 'sm-reviewer.toml')));
    assert.equal((await runSync({ root, files, check: true })).ok, true);
    writeFileSync(join(dir, 'alpha.md'), part('Second rule.'));
    const drift = await runSync({ root, files, check: true });
    assert.equal(drift.ok, false);
    assert.equal(drift.changed.length, 3);
    await runSync({ root, files });
    assert.match(readFileSync(join(root, '.claude', 'agents', 'sm-alpha.md'), 'utf8'), /Second rule\./);
    writeFileSync(join(root, '.claude', 'agents', 'sm-finder.md'), 'my own finder');
    const guarded = await runSync({ root, files });
    assert.deepEqual(guarded.refused, ['.claude/agents/sm-finder.md']);
    assert.equal(readFileSync(join(root, '.claude', 'agents', 'sm-finder.md'), 'utf8'), 'my own finder');
    assert.equal(readdirSync(join(root, '.gemini', 'agents')).length, 6);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('the release gate: silent where the agent files were never generated, a failure when they drift from the map', async () => {
  const { execFileSync } = await import('node:child_process');
  const { checkAgentFilesFresh } = await import('../scripts/release-gate.mjs');
  const root = mkdtempSync(join(tmpdir(), 'sm-agents-gate-'));
  try {
    const dir = join(root, 'docs', 'architecture');
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'README.md'), '# Parts\n\n## Engine\n\n- [Alpha](alpha.md)\n');
    const part = (rule) => `# Alpha\n\nAlpha works.\n\n## Where in the code\n\n- \`server/alpha/\`\n\n## Rules that must not break\n\n- ${rule}\n\n## What's missing\n\n- [ ] **Claude:** x \`al01\`\n`;
    writeFileSync(join(dir, 'alpha.md'), part('First rule.'));
    execFileSync('git', ['init', '-q'], { cwd: root });
    execFileSync('git', ['add', '-A'], { cwd: root });
    assert.deepEqual(await checkAgentFilesFresh(root), [], 'never generated: nothing to keep fresh');
    await runSync({ root });
    execFileSync('git', ['add', '-A'], { cwd: root });
    assert.deepEqual(await checkAgentFilesFresh(root), []);
    writeFileSync(join(dir, 'alpha.md'), part('Changed rule.'));
    const res = await checkAgentFilesFresh(root);
    assert.equal(res.length, 1);
    assert.equal(res[0].id, 'agent-files');
    assert.match(res[0].message, /node scripts\/sync-agents\.mjs/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('the file list is stable across git add and commit: tracked, new and not ignored, never an ignored file', async () => {
  const { execFileSync } = await import('node:child_process');
  const { trackedFiles } = await import('../server/ai/specialists-load.mjs');
  const root = mkdtempSync(join(tmpdir(), 'sm-agents-files-'));
  try {
    execFileSync('git', ['init', '-q'], { cwd: root });
    writeFileSync(join(root, '.gitignore'), 'secret.txt\n');
    writeFileSync(join(root, 'a.mjs'), '');
    writeFileSync(join(root, 'secret.txt'), '');
    const before = await trackedFiles(root);
    assert.deepEqual(before, ['.gitignore', 'a.mjs']);
    execFileSync('git', ['add', '-A'], { cwd: root });
    assert.deepEqual(await trackedFiles(root), before, 'adding changes nothing');
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
