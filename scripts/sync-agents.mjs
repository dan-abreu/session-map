import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { agentSpecs } from '../server/ai/specialists.mjs';
import { loadSpecialists } from '../server/ai/specialists-load.mjs';
import { MARKER, VENDORS, buildAgentFiles, checkAgentFiles } from '../server/ai/agent-files.mjs';

// Writes the specialist agent files of a project for every AI that reads them (id158, or68): one specialist per code part
// of its architecture map, plus the native roles. `--check` writes nothing and exits 1 when a file is missing, changed or
// stale — the release gate's door against an agent file that no longer follows the map.
//   node scripts/sync-agents.mjs [--root <dir>] [--vendors claude,gemini,codex] [--check]

const read = (path) => { try { return readFileSync(path, 'utf8'); } catch { return null; } };
const list = (dir) => { try { return readdirSync(dir); } catch { return []; } };

export async function runSync({ root, vendors = VENDORS, check = false, files = null, io = {} } = {}) {
  const loaded = await loadSpecialists({ root, files, read: io.read ?? read });
  if (!loaded.ok) return { ok: false, error: loaded.error === 'no-map' ? 'The architecture map must be in the working tree (docs/architecture); a map read from the main branch is not written from.' : 'The tracked files of the project could not be listed (is it a git repository?).' };
  const { specialists } = loaded;
  const specs = agentSpecs({ specialists });
  const built = buildAgentFiles(specs, { vendors });
  const status = checkAgentFiles(built, { root, read: io.read ?? read, list: io.list ?? list, vendors });
  const summary = { specialists: specialists.length, specs: specs.length, files: built.length, ...status };
  if (check) return { ok: status.clean, check: true, ...summary };
  const write = io.write ?? ((path, content) => { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, content); });
  const remove = io.remove ?? ((path) => rmSync(path, { force: true }));
  const refused = [];
  for (const f of built) {
    const abs = join(root, f.path);
    const have = (io.read ?? read)(abs);
    if (have === f.content) continue;
    // A file of the same name that this tool did not write is somebody's own agent: it is never overwritten.
    if (have !== null && !have.includes(MARKER)) { refused.push(f.path); continue; }
    write(abs, f.content);
  }
  for (const path of status.stale) remove(join(root, path));
  return { ok: !refused.length, refused, written: status.missing.length + status.changed.length - refused.length, removed: status.stale.length, ...summary };
}

async function main() {
  const { values } = parseArgs({ options: { root: { type: 'string' }, vendors: { type: 'string' }, check: { type: 'boolean' } } });
  const root = resolve(values.root ?? process.cwd());
  if (!existsSync(root)) { console.error(`No such folder: ${root}`); process.exit(2); }
  const vendors = values.vendors ? values.vendors.split(',').map((v) => v.trim()).filter(Boolean) : VENDORS;
  const bad = vendors.filter((v) => !VENDORS.includes(v));
  if (bad.length) { console.error(`Unknown vendor: ${bad.join(', ')} (known: ${VENDORS.join(', ')})`); process.exit(2); }
  const res = await runSync({ root, vendors, check: Boolean(values.check) });
  if (res.error) { console.error(res.error); process.exit(2); }
  if (res.check) {
    for (const [label, paths] of [['missing', res.missing], ['changed', res.changed], ['stale', res.stale]]) for (const p of paths) console.log(`${label}: ${p}`);
    console.log(res.ok ? `Agent files follow the map (${res.specialists} specialists, ${res.files} files).` : 'Agent files are out of date: run node scripts/sync-agents.mjs');
    process.exit(res.ok ? 0 : 1);
  }
  for (const p of res.refused ?? []) console.log(`not overwritten (not generated by session-map): ${p}`);
  console.log(`${res.specialists} specialists, ${res.specs} agents, ${res.files} files: ${res.written} written, ${res.removed} removed.`);
  process.exit(res.ok ? 0 : 1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
