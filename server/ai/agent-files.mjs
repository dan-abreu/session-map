import { join, posix } from 'node:path';
import { CONFIG } from './specialists.mjs';

// The native agent files (id158, or68): each AI that can define an agent in a file gets the same spec spelled in its own
// format. Claude Code reads .claude/agents/*.md, Gemini CLI .gemini/agents/*.md, Codex .codex/agents/*.toml (fields checked
// on each vendor's documentation on 2026-10-15). Pure: specs in, {path, content} out — the sync script does the writing.
// The model and level go only where the file's AI uses the policy's names (Claude); Gemini and Codex inherit the model the
// person chose for that AI, because a model name is one company's. DeepSeek runs through the Claude files or the
// executor's brief (agents-run.mjs); an AI with only an API takes the card as its system text.

export const VENDORS = Object.freeze(['claude', 'gemini', 'codex']);
export const MARKER = 'generated by session-map';
const NOTE = `${MARKER} (scripts/sync-agents.mjs) from the architecture map and server/ai/agents.json. Do not edit by hand: edit the source, then run node scripts/sync-agents.mjs.`;

const DIRS = { claude: '.claude/agents', gemini: '.gemini/agents', codex: '.codex/agents' };
const EXT = { claude: 'md', gemini: 'md', codex: 'toml' };

// An empty list would not mean "no tools" to the AI: it can mean "inherit them all". A class the vendor has no tool for is a
// broken config, not a quiet default.
function toolsOf(vendor, classes, config) {
  const tools = classes.flatMap((c) => config.toolClasses[vendor]?.[c] ?? []);
  if (!tools.length) throw new Error(`agent-files: no ${vendor} tools for the classes ${classes.join(', ')}`);
  return tools;
}

export function renderClaude(spec, config = CONFIG) {
  return [
    '---',
    `name: ${spec.id}`,
    `description: ${JSON.stringify(spec.description)}`,
    `tools: ${toolsOf('claude', spec.classes, config).join(', ')}`,
    `model: ${spec.model}`,
    `effort: ${spec.effort}`,
    '---',
    '',
    `<!-- ${NOTE} -->`,
    '',
    spec.system,
    '',
  ].join('\n');
}

export function renderGemini(spec, config = CONFIG) {
  return [
    '---',
    `name: ${spec.id}`,
    `description: ${JSON.stringify(spec.description)}`,
    'tools:',
    ...toolsOf('gemini', spec.classes, config).map((t) => `  - ${t}`),
    '---',
    '',
    `<!-- ${NOTE} -->`,
    '',
    spec.system,
    '',
  ].join('\n');
}

// A TOML multi-line basic string: backslashes doubled, a run of three quotes broken.
const tomlMulti = (s) => `"""\n${s.replaceAll('\\', '\\\\').replaceAll('"""', '\\"\\"\\"')}\n"""`;

// Codex cannot narrow tools or the sandbox per agent (they follow the parent session), so the file carries the instructions
// only; what holds a Codex run is the isolated copy and the exit gates of the executor (agents-run.mjs).
export function renderCodex(spec) {
  return [
    `# ${NOTE}`,
    `name = ${JSON.stringify(spec.id)}`,
    `description = ${JSON.stringify(spec.description)}`,
    `developer_instructions = ${tomlMulti(spec.system)}`,
    '',
  ].join('\n');
}

const RENDER = { claude: renderClaude, gemini: renderGemini, codex: renderCodex };

// -> [{vendor, path, content}] with the path relative to the project root, in a stable order.
export function buildAgentFiles(specs, { vendors = VENDORS, config = CONFIG } = {}) {
  const out = [];
  for (const vendor of vendors) {
    if (!RENDER[vendor]) throw new Error(`agent-files: unknown vendor ${vendor}`);
    for (const spec of specs) out.push({ vendor, path: posix.join(DIRS[vendor], `${spec.id}.${EXT[vendor]}`), content: RENDER[vendor](spec, config) });
  }
  return out;
}

// Compares the files on disk with the expected ones. read(path) → text or null; list(dir) → file names (or []). A stale
// file is one this tool generated (it carries the marker) and the spec no longer has: it is the only kind ever removed.
export function checkAgentFiles(files, { root, read, list, vendors = VENDORS, config = CONFIG }) {
  const missing = [];
  const changed = [];
  for (const f of files) {
    const have = read(join(root, f.path));
    if (have === null) missing.push(f.path);
    else if (have !== f.content) changed.push(f.path);
  }
  const wanted = new Set(files.map((f) => f.path));
  const stale = [];
  for (const vendor of vendors) {
    for (const name of list(join(root, DIRS[vendor]))) {
      const path = posix.join(DIRS[vendor], name);
      if (!name.startsWith(config.prefix) || wanted.has(path)) continue;
      if (String(read(join(root, path)) ?? '').includes(MARKER)) stale.push(path);
    }
  }
  return { missing, changed, stale, clean: !missing.length && !changed.length && !stale.length };
}
