export const LANGS = { en, 'pt-BR': ptBR };

export function pickLang(saved, navigatorLang) {
  if (saved && LANGS[saved]) return saved;
  return /^pt\b/i.test(navigatorLang || '') ? 'pt-BR' : 'en';
}

export function translator(lang) {
  const dict = LANGS[lang] || en;
  const plural = new Intl.PluralRules(lang);
  const fill = (s, vars) => s.replace(/\{(\w+)\}/g, (_, k) => (vars && k in vars ? vars[k] : `{${k}}`));
  const t = (key, vars) => fill(dict[key] ?? en[key] ?? key, vars);
  t.count = (key, n) => {
    const form = plural.select(n) === 'one' ? 'one' : 'other';
    return t(`${key}.${form}`, { n });
  };
  return t;
}
